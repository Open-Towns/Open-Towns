$ErrorActionPreference = "Stop"

$root = Resolve-Path (Join-Path $PSScriptRoot "..")

Push-Location $root

try {

    Write-Host "Building Open Towns API JAR..."

    & .\gradlew.bat clean apiJar

    if ($LASTEXITCODE -ne 0) {
        throw "Gradle apiJar build failed."
    }

    $jarPath = Join-Path $root "build\libs\opentowns-api.jar"

    if (-not (Test-Path $jarPath)) {
        throw "API JAR not found: $jarPath"
    }

    Write-Host "Inspecting API JAR..."

    $jarEntries = & jar tf $jarPath

    if ($LASTEXITCODE -ne 0) {
        throw "Could not inspect API JAR."
    }

    #
    # Guard against runtime implementation classes leaking
    # into the distributable SDK.
    #
    $forbiddenPatterns = @(
        "xaos/api/GameApiBootstrap.class",
        "xaos/api/mods/JavaModLoader",
        "xaos/api/mods/LoadedJavaMod",
        "xaos/api/mods/DefaultModLogger",
        "xaos/api/definitions/DefinitionSnapshotFactory"
    )

    foreach ($pattern in $forbiddenPatterns) {

        $match = $jarEntries |
            Where-Object {
                $_ -like "$pattern*"
            }

        if ($match) {
            throw "Runtime-only class leaked into API JAR: $pattern"
        }
    }

    #
    # ModResourceScope is deliberately present because
    # ModContext references it internally, but it is
    # package-private and must not appear in the reference.
    #

    $classNames = $jarEntries |
        Where-Object {
            $_.StartsWith("xaos/api/") -and
            $_.EndsWith(".class") -and
            -not $_.EndsWith("package-info.class") -and
            -not $_.EndsWith("module-info.class")
        } |
        ForEach-Object {
            $_.
                Replace("/", ".").
                Replace(".class", "")
        } |
        Sort-Object -Unique

    $publicTypes = @()

    foreach ($className in $classNames) {

        $output = @(
            & javap `
                -public `
                -constants `
                -classpath $jarPath `
                $className
        )

        if ($LASTEXITCODE -ne 0) {
            throw "javap failed for $className"
        }

        #
        # javap prints package-private classes too.
        # Only include types whose declaration is public.
        #
        $publicDeclaration = $output |
            Where-Object {
                $_ -match "^public\s+"
            } |
            Select-Object -First 1

        if ($null -eq $publicDeclaration) {
            continue
        }

        #
        # Remove the unhelpful:
        # Compiled from "Foo.java"
        #
        $cleanOutput = $output |
            Where-Object {
                $_ -notmatch '^Compiled from '
            }

        $publicTypes += [PSCustomObject]@{
            Name   = $className
            Output = ($cleanOutput -join "`n")
        }
    }

    #
    # API freeze checks.
    #

    $gameApi = $publicTypes |
        Where-Object {
            $_.Name -eq "xaos.api.GameApi"
        } |
        Select-Object -First 1

    if ($null -eq $gameApi) {
        throw "GameApi is missing from the API JAR."
    }

    if ($gameApi.Output -match "static xaos\.api\.GameApi get\(\)") {
        throw "GameApi.get() is still publicly exposed."
    }

    $uiRegistration = $publicTypes |
        Where-Object {
            $_.Name -eq "xaos.api.ui.UiActionRegistration"
        }

    if ($null -eq $uiRegistration) {
        throw "UiActionRegistration is missing from the API."
    }

    $fluidApi = $publicTypes |
        Where-Object {
            $_.Name -eq "xaos.api.fluids.FluidApi"
        } |
        Select-Object -First 1

    if ($null -eq $fluidApi) {
        throw "FluidApi is missing from the API."
    }

    if ($fluidApi.Output -notmatch "supports\(xaos\.api\.definitions\.DefinitionId\)") {
        throw "FluidApi.supports() is missing."
    }

    #
    # Generate Markdown.
    #

    $docsDirectory = Join-Path $root "docs\modding"

    New-Item `
        -ItemType Directory `
        -Force `
        -Path $docsDirectory |
        Out-Null

    $outputPath = Join-Path $docsDirectory "API_REFERENCE.md"

    $markdown = New-Object System.Collections.Generic.List[string]

    $markdown.Add("# Open Towns SDK API Reference")
    $markdown.Add("")
    $markdown.Add("> Generated automatically from ``opentowns-api.jar``. Do not edit this file manually.")
    $markdown.Add("")
    $markdown.Add("This reference contains the public Java surface exposed to Open Towns mods.")
    $markdown.Add("")
    $markdown.Add("Package-private and runtime implementation classes are intentionally omitted.")
    $markdown.Add("")
    $markdown.Add("Public types: **$($publicTypes.Count)**")
    $markdown.Add("")

    $grouped = $publicTypes |
        Group-Object {
            $lastDot = $_.Name.LastIndexOf(".")

            if ($lastDot -lt 0) {
                return "(default)"
            }

            return $_.Name.Substring(
                0,
                $lastDot
            )
        } |
        Sort-Object Name

    foreach ($package in $grouped) {

        $markdown.Add("## ``$($package.Name)``")
        $markdown.Add("")

        foreach ($type in ($package.Group | Sort-Object Name)) {

            $simpleName = $type.Name.Substring(
                $type.Name.LastIndexOf(".") + 1
            )

            $markdown.Add("### ``$simpleName``")
            $markdown.Add("")
            $markdown.Add('```java')
            $markdown.Add($type.Output)
            $markdown.Add('```')
            $markdown.Add("")
        }
    }

    Set-Content `
        -Path $outputPath `
        -Value $markdown `
        -Encoding UTF8

    Write-Host ""
    Write-Host "API reference generated successfully."
    Write-Host "Public types: $($publicTypes.Count)"
    Write-Host "Output: $outputPath"
}
finally {

    Pop-Location
}