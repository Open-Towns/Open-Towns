package xaos.panels.menus;

public final class GeneratedMenuItemsDefinition {

    private final String id;
    private final String provider;

    public GeneratedMenuItemsDefinition(String id, String provider) {
        this.id = id;
        this.provider = provider;
    }

    public String getId() {
        return id;
    }

    public String getProvider() {
        return provider;
    }
}